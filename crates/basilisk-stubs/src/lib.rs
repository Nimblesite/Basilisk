// Generated by `build.rs` — the offline baseline stdlib name-set
// (`static STDLIB_MODULES: phf::Set<&'static str>`), overridden at runtime by
// the cloned typeshed's `stdlib/VERSIONS` ([STUBRES-TYPESHED-BASELINE]).
include!(concat!(env!("OUT_DIR"), "/stdlib_set.rs"));

// Generated by `build.rs` — the offline baseline `types-<dist>` map
// (`static STUB_DISTRIBUTIONS: phf::Map<&'static str, &'static str>`),
// overridden at runtime by the cloned typeshed's `stubs/<DIST>/` tree.
include!(concat!(env!("OUT_DIR"), "/stub_map.rs"));

/// Check whether a top-level module name belongs to the `CPython` 3.12 stdlib.
///
/// Extracts the root segment (before the first `.`) and checks it against the
/// offline baseline name-set. O(1) lookup via perfect hashing.
// Implements [STUBRES-TYPESHED] — this set is the offline baseline built by
// `build.rs` into a `phf` set for O(1) lookup; the runtime clone's
// `stdlib/VERSIONS` supersedes it. The stdlib list is derived data, not a
// maintained list.
#[must_use]
pub fn is_stdlib_module(module_name: &str) -> bool {
    let root = module_name.split('.').next().unwrap_or(module_name);
    STDLIB_MODULES.contains(root)
}

/// Look up the typeshed stub distribution (`types-<dist>`) that provides types
/// for a given import.
///
/// Extracts the root segment (before the first `.`) and checks it against the
/// `types-<dist>` map (the runtime clone's `stubs/<DIST>/` tree, or the offline
/// baseline when no clone is available). Returns the `PyPI` distribution name
/// installable via `uv add --dev` (e.g. `requests` → `types-requests`, `yaml` →
/// `types-PyYAML`). Returns `None` when no typeshed stub distribution is known —
/// either the package ships inline `py.typed` types or no stubs exist — so
/// callers can avoid suggesting a package that would fail to resolve on `PyPI`.
// Implements [STUBRES-PEP561] step 3 (stub-only packages) — names the
// `types-<dist>` distribution the resolver/quick-fix installs to satisfy a
// stub-only import; backed by the `build.rs`-generated typeshed stub map.
#[must_use]
pub fn typeshed_stub_distribution(module_name: &str) -> Option<&'static str> {
    let root = module_name.split('.').next().unwrap_or(module_name);
    STUB_DISTRIBUTIONS.get(root).copied()
}

/// Whether the package containing `resolved_path` ships a PEP 561 `py.typed`
/// marker (i.e. opts in to inline type distribution).
///
/// Walks up from the resolved file looking for a `py.typed` file, stopping at
/// the `site-packages` boundary — installed packages are its direct children,
/// so the marker never lives at or above that level. Implements [STUBRES-ENGINE].
// Implements [STUBRES-PEP561] step 4 (inline-typed packages) — detects the
// PEP 561 `py.typed` opt-in marker that distinguishes an inline-typed package
// from an untyped one.
#[must_use]
pub fn has_py_typed_marker(resolved_path: &std::path::Path) -> bool {
    let mut dir = resolved_path.parent();
    while let Some(current) = dir {
        if current.file_name() == Some(std::ffi::OsStr::new("site-packages")) {
            return false;
        }
        if current.join("py.typed").is_file() {
            return true;
        }
        dir = current.parent();
    }
    false
}

/// Look up the type annotation string for a built-in symbol.
///
/// Returns type information for Python built-in types.
/// Unknown names return `None`.
// Implements [STUBRES-TYPESHED] — `lookup_builtin()` over Python primitives
// (part of the typeshed-backed standard-library surface).
#[must_use]
pub fn lookup_builtin(name: &str) -> Option<&'static str> {
    match name {
        "int" => Some("int"),
        "float" => Some("float"),
        "str" => Some("str"),
        "bytes" => Some("bytes"),
        "bool" => Some("bool"),
        "list" => Some("list"),
        "dict" => Some("dict"),
        "set" => Some("set"),
        "tuple" => Some("tuple"),
        "frozenset" => Some("frozenset"),
        "type" => Some("type"),
        "object" => Some("object"),
        "None" => Some("None"),
        "complex" => Some("complex"),
        "range" => Some("range"),
        "bytearray" => Some("bytearray"),
        "memoryview" => Some("memoryview"),
        _ => None,
    }
}

