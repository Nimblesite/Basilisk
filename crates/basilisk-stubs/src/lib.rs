//! Implements [STUBRES-ENGINE]. See docs/specs/CHECKER-STUB-RESOLUTION-SPEC.md#STUBRES-ENGINE
//! Standard-library typeshed resolution for Basilisk: the runtime
//! `python/typeshed` clone/cache is canonical; the compiled data below is the
//! offline day-one baseline it overrides ([STUBRES-TYPESHED-BASELINE]).
//!
//! Provides:
//! - O(1) stdlib module-name recognition over the offline baseline (a `phf`
//!   set), superseded at runtime by the cloned typeshed's `stdlib/VERSIONS`
//! - Built-in type lookup for Python primitives
//! - Stub resolution data model ([`StubResolution`], [`StubSource`], [`StubTier`])

