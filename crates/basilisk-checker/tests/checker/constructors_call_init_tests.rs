/// Regression for issue #44: a class inheriting from an unresolved *external*
/// base (e.g. pydantic v2 `BaseModel`, whose `__init__` is generated by its
/// metaclass) must NOT be reported as "inherits only from `object`". The
/// checker cannot see the base's constructor, so it must stay conservative and
/// not emit constructors_call_init — otherwise every keyword construction of a Pydantic
/// model is a false positive.
#[test]
fn no_false_positive_on_external_base() -> Result<(), Box<dyn std::error::Error>> {
    let source = r#"
from pydantic import BaseModel


class BundleUploadResponse(BaseModel):
    bundle_id: int
    sha256: str


BundleUploadResponse(bundle_id=1, sha256="abc")
"#;
    let diags = run(source)?;
    assert!(
        !codes(&diags).contains(&"constructors_call_init"),
        "constructing a subclass of an unresolved external base must not fire E0111; got: {:?}",
        codes(&diags)
    );
    Ok(())
}
